import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createEngine } from '../frontend/js/wasm-runtime.js';

const bytes = readFileSync(new URL('../frontend/wasm/engine.wasm', import.meta.url));
const engine = await createEngine(bytes);
const call = (method, path, body) => engine.request(method, path, body == null ? '' : JSON.stringify(body));
const get = path => call('GET', path).data;
const post = (path, body = {}) => call('POST', path, body);
assert.equal(get('/api/health').symbol, 'TCX');
assert.equal(post('/api/scenario', { name: 'worked-example' }).data.trades, 4);
let book = get('/api/book');
assert.deepEqual(book.bids.map(({ price, qty }) => [price, qty]), [[101, 30]]);
assert.deepEqual(book.asks.map(({ price, qty }) => [price, qty]), [[102, 40]]);
assert.equal(get('/api/summary').volume, 250);
assert.equal(get('/api/trades').trades.length, 4);
const cutoff = get('/api/trades').trades[0].time_ms;
assert.ok(cutoff > 2 ** 31);
assert.ok(get(`/api/trades?since_ms=${cutoff}`).trades.length > 0);
assert.equal(get(`/api/trades?since_ms=${cutoff + 1}`).trades.length, 0);
assert.equal(get(`/api/summary?since_ms=${cutoff + 1}`).volume, 0);
assert.ok(get('/api/candles').candles.length > 0);
assert.equal(get('/api/check').ok, true);
assert.ok(get('/api/events?since=1').events.length > 0);
assert.equal(get('/api/dsa/tree?side=buy').nodes.length, 1);
assert.equal(get('/api/dsa/hash?order_id=6').lookup.found, true);
assert.equal(get('/api/dsa/hash?order_id=4294967296').lookup.order_id, 4294967296);

assert.equal(post('/api/reset').events[0].type, 'reset');
const sell = post('/api/orders', { side: 'sell', price: 100, qty: 80, trader: 'S1' });
assert.equal(sell.events[0].type, 'command');
assert.ok(sell.events.some(event => event.type === 'trace' && event.data.events.length));
const second = post('/api/orders', { side: 'sell', price: 100, qty: 70, trader: 'S2' });
const buy = post('/api/orders', { side: 'buy', price: 100, qty: 100, trader: 'B1' });
assert.deepEqual(buy.data.fills.map(fill => [fill.maker_id, fill.qty]), [[sell.data.order.id, 80], [second.data.order.id, 20]]);
const replaced = post(`/api/orders/${second.data.order.id}/replace`, { qty: 30, price: 101 });
assert.equal(replaced.data.replaced.status, 'replaced');
assert.equal(post(`/api/orders/${replaced.data.order.id}/cancel`).data.order.status, 'cancelled');
assert.equal(post('/api/orders', { side: 'buy', price: 100.01, qty: 1 }).status, 422);
assert.equal(get('/api/check').ok, true);
assert.equal(post('/api/scenario', { name: 'random', seed: 42, count: 5000 }).data.ok, true);
assert.equal(get('/api/check').ok, true);
assert.ok(get('/api/stats').ok);
assert.ok(get('/api/events?since=4294967296').events.length === 0);
const isolated = await createEngine(bytes);
assert.equal(isolated.request('GET', '/api/book').data.active_orders, 0);
assert.ok(get('/api/book').active_orders > 0);
console.log('WebAssembly API checks passed: worked example, 64-bit filters, FIFO, replace/cancel, trace events, 5,000-command stress, isolated sessions.');
