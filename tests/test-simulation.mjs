import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createSimulation } from '../frontend/simulation/adapter/runtime.js';

let current = Date.now();
const simulation = await createSimulation(readFileSync(new URL('../frontend/simulation/adapter/engine.wasm', import.meta.url)), { now: () => current });
const request = (method, path, body, token = '') => simulation.request(method, path, body ? JSON.stringify(body) : '', token);
const before = request('GET', '/api/summary').data;
assert.ok(before.total_trades > 100);
const login = request('POST', '/api/auth/login', { username: 'demo', password: 'demo1234' });
assert.equal(login.status, 200);
assert.ok(login.data.token);
const token = login.data.token;
assert.equal(request('GET', '/api/auth/me', null, token).data.user.username, 'demo');
const botsBefore = request('GET', '/api/sim', null, token).data.sim;
assert.equal(botsBefore.running, true);
current += 5000;
const events = simulation.tick();
assert.ok(events.some(event => event.type === 'command'));
assert.ok(request('GET', '/api/summary').data.total_trades >= before.total_trades);
assert.equal(request('GET', '/api/check', null, token).data.ok, true);
assert.equal(request('POST', '/api/sim', { running: false, mode: 'bull', rate: 5 }, token).data.ok, true);
const paused = request('GET', '/api/sim', null, token).data.sim;
assert.equal(paused.running, false);
assert.equal(paused.mode, 'bull');
const book = request('GET', '/api/book').data;
const buy = request('POST', '/api/orders', { side: 'buy', price: book.best_ask, qty: 1 }, token);
assert.equal(buy.status, 200, JSON.stringify(buy.data));
assert.ok(buy.data.fills.length > 0);
assert.equal(request('GET', `/api/trades?since_ms=${current + 100000}`, null, token).data.trades.length, 0);
assert.equal(request('GET', '/api/check', null, token).data.ok, true);
assert.equal(request('POST', '/api/auth/login', { username: 'demo', password: 'bad-pass' }).status, 401);
assert.equal(request('POST', '/api/auth/register', { username: 'newstudent', password: 'practice123' }).data.ok, true);
console.log('Updated upstream simulation passed: seeded history, C demo sign-in, live bot ticks, pause/bull controls, matching, timestamp filtering, registration and invariant checks.');
